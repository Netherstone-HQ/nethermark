// Writes the icon sets from Phosphor Icons, one file per weight. Run with
// `pnpm icons` after changing the list or updating @phosphor-icons/core.
// The core uses regular; each weight is also its own entry point,
// `@netherstone/nethermark/icons/<weight>`, so a bundle carries only the
// sets it imports.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { URL } from "node:url";

/** Every Phosphor icon the package draws, by the name the `icons` option uses. */
const ICONS = {
  bold: "text-b",
  italic: "text-italic",
  strikethrough: "text-strikethrough",
  inlineCode: "code",
  heading1: "text-h-one",
  heading2: "text-h-two",
  heading3: "text-h-three",
  heading4: "text-h-four",
  heading5: "text-h-five",
  heading6: "text-h-six",
  bulletList: "list-bullets",
  orderedList: "list-numbers",
  taskList: "list-checks",
  quote: "quotes",
  link: "link-simple",
  image: "image",
  codeBlock: "code-block",
  table: "table",
  horizontalRule: "minus",
  more: "dots-three",
  tableMenu: "rows",
  preview: "eye",
};

const WEIGHTS = ["regular", "fill", "bold", "light", "thin"];

// The package doesn't export its files, so they're read from where pnpm links it.
const root = new URL("../node_modules/@phosphor-icons/core/", import.meta.url).pathname;
const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
const out = new URL("../src/icons/", import.meta.url);
mkdirSync(out, { recursive: true });

for (const weight of WEIGHTS) {
  const lines = Object.entries(ICONS).map(([name, icon]) => {
    const file = weight === "regular" ? `${icon}.svg` : `${icon}-${weight}.svg`;
    const svg = readFileSync(join(root, "assets", weight, file), "utf8")
      .trim()
      .replace("<svg ", '<svg class="nme-icon" aria-hidden="true" focusable="false" ');
    return `  ${name}: ${JSON.stringify(svg)},`;
  });

  writeFileSync(
    new URL(`${weight}.ts`, out),
    `// Generated by scripts/icons.mjs from Phosphor Icons ${version} (${weight}), MIT
// licensed: see THIRD_PARTY_NOTICES.md. Don't edit by hand.

/** Every icon the package draws, in Phosphor's ${weight} weight, as inline SVG strings in currentColor. Pass it as the \`icons\` option. */
export const icons = {
${lines.join("\n")}
} as const;
`,
  );
}
