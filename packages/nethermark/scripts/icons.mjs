// Writes the icon files from Phosphor's fill icons. Run with `pnpm icons`
// after changing a list or updating @phosphor-icons/core. Each entry point
// gets its own file, so the core bundle carries only the toolbar's icons.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { URL } from "node:url";

const TOOLBAR = {
  bold: "text-b",
  italic: "text-italic",
  strikethrough: "text-strikethrough",
  inlineCode: "code",
  heading1: "text-h-one",
  heading2: "text-h-two",
  heading3: "text-h-three",
  heading4: "text-h-four",
  heading5: "text-h-five",
  heading6: "text-h-six",
  bulletList: "list-bullets",
  orderedList: "list-numbers",
  taskList: "list-checks",
  quote: "quotes",
  link: "link-simple",
  image: "image",
  codeBlock: "code-block",
  table: "table",
  horizontalRule: "minus",
  more: "dots-three",
  tableMenu: "rows",
};

const FILES = {
  "../src/toolbar/icons.ts": { doc: "The toolbar's icons", icons: TOOLBAR },
  "../src/preview/icons.ts": { doc: "The preview's icons", icons: { preview: "eye" } },
};

// The package doesn't export its files, so they're read from where pnpm links it.
const root = new URL("../node_modules/@phosphor-icons/core/", import.meta.url).pathname;
const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;

for (const [file, { doc, icons }] of Object.entries(FILES)) {
  const lines = Object.entries(icons).map(([name, icon]) => {
    const svg = readFileSync(join(root, "assets", "fill", `${icon}-fill.svg`), "utf8")
      .trim()
      .replace("<svg ", '<svg class="nme-icon" aria-hidden="true" focusable="false" ');
    return `  ${name}: ${JSON.stringify(svg)},`;
  });

  writeFileSync(
    new URL(file, import.meta.url),
    `// Generated by scripts/icons.mjs from Phosphor Icons ${version} (fill), MIT
// licensed: see THIRD_PARTY_NOTICES.md. Don't edit by hand.

/** ${doc}, as inline SVG strings drawn in currentColor. */
export const icons = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof icons;
`,
  );
}
