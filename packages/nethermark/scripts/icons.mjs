// Writes src/toolbar/icons.ts from Phosphor's fill icons. Run with
// `pnpm icons` after changing the list or updating @phosphor-icons/core.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { URL } from "node:url";

const ICONS = {
  bold: "text-b",
  italic: "text-italic",
  strikethrough: "text-strikethrough",
  inlineCode: "code",
  heading1: "text-h-one",
  heading2: "text-h-two",
  heading3: "text-h-three",
  heading4: "text-h-four",
  heading5: "text-h-five",
  heading6: "text-h-six",
  bulletList: "list-bullets",
  orderedList: "list-numbers",
  taskList: "list-checks",
  quote: "quotes",
  link: "link-simple",
  image: "image",
  codeBlock: "code-block",
  table: "table",
  horizontalRule: "minus",
  more: "dots-three",
  tableMenu: "rows",
};

// The package doesn't export its files, so they're read from where pnpm links it.
const root = new URL("../node_modules/@phosphor-icons/core/", import.meta.url).pathname;
const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;

const lines = Object.entries(ICONS).map(([name, file]) => {
  const svg = readFileSync(join(root, "assets", "fill", `${file}-fill.svg`), "utf8")
    .trim()
    .replace("<svg ", '<svg class="nme-icon" aria-hidden="true" focusable="false" ');
  return `  ${name}: ${JSON.stringify(svg)},`;
});

writeFileSync(
  new URL("../src/toolbar/icons.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from Phosphor Icons ${version} (fill), MIT
// licensed: see THIRD_PARTY_NOTICES.md. Don't edit by hand.

/** The toolbar's icons, as inline SVG strings drawn in currentColor. */
export const icons = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof icons;
`,
);
